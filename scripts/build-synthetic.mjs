// Generates data/synthetic-history.json: a SIMULATED return history used only to illustrate
// the merchant heatmap before any live sessions exist. It is labelled "synthetic demo data"
// everywhere it is shown and is never mixed into live KPIs.
//
// Method: simulate purchases by shoppers with random tone profiles (fixed seed). The chance
// that a purchase comes back for a colour reason rises with the matcher's mismatch score for
// that product and profile. So the pattern in the heatmap comes from the matching model's
// assumptions, not from real data. It contains no outcomes (exchange/refund), so it cannot
// be mistaken for conversion results.
import { writeFileSync } from 'node:fs';
import { Catalog } from '../server/store/catalog.js';
import { PROFILE_KEYS, representativeProfile } from '../server/store/insights.js';
import { scoreProduct } from '../server/color/match.js';

const SEED = 20261102;
function mulberry32(a) {
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rand = mulberry32(SEED);
const pick = (arr) => arr[Math.floor(rand() * arr.length)];

const catalog = new Catalog();
const profiles = Object.fromEntries(PROFILE_KEYS.map((k) => [k, representativeProfile(k)]));
// Simulate a store selling more of its three hero products (the demo orders).
const heroes = ['lip-l01', 'fdn-3w', 'dress-wrap-camel'];
const thresholds = { lipstick: [14, 4], foundation: [6, 2], dress: [3, 1.2] };

const records = [];
const PURCHASES = 1500;
for (let i = 0; i < PURCHASES; i++) {
  const product = rand() < 0.35 ? catalog.product(pick(heroes)) : pick(catalog.products);
  const profileKey = pick(PROFILE_KEYS);
  const { score } = scoreProduct(product, profiles[profileKey], null);
  const [t, s] = thresholds[product.category];
  const pReturn = 0.45 / (1 + Math.exp(-(score - t) / s));
  if (rand() < pReturn) {
    const daysAgo = Math.floor(rand() * 60);
    records.push({
      productId: product.id,
      category: product.category,
      price: product.price,
      profileKey,
      reason: product.category === 'dress' ? 'colour_didnt_suit' : 'wrong_shade',
      at: new Date(Date.UTC(2026, 10, 2) - daysAgo * 86400000).toISOString().slice(0, 10),
    });
  }
}

const out = {
  label: 'Synthetic demo data',
  disclaimer:
    'Simulated return history generated by scripts/build-synthetic.mjs (fixed seed). Not real customers, not real results. Used only to illustrate the heatmap and insight cards.',
  seed: SEED,
  simulatedPurchases: PURCHASES,
  records,
};
writeFileSync(new URL('../data/synthetic-history.json', import.meta.url), JSON.stringify(out, null, 1) + '\n');
console.log(`synthetic returns: ${records.length} from ${PURCHASES} simulated purchases`);
